"""
안전지수 계산 아주 쉬운 버전

목표:
- 지도 전체를 계산하지 않음
- 격자도 아직 만들지 않음
- 딱 한 위치를 기준으로 주변 1km 안의 시설을 세어봄
- 그걸로 임시 안전점수와 등급을 만들어봄

즉, 전체 프로젝트의 아주 작은 버전이다.
"""

import pandas as pd
import numpy as np
from pathlib import Path


# ============================================================
# 1단계. 테스트용 시설 데이터 만들기
# ============================================================

"""
원래는 데이터 파트가 facilities_clean.csv를 줘야 한다.

그런데 아직 최종 데이터가 없으니까,
지금은 우리가 직접 작은 표를 만들어서 연습한다.

이 표의 의미:
- CCTV 하나
- 가로등 하나
- 비상벨 하나
- 파출소 하나

각 시설은 위도, 경도, 시설유형, count를 가진다.
"""

facilities = pd.DataFrame([
    {
        "위도": 37.5400,
        "경도": 127.0830,
        "시설유형": "CCTV",
        "주소": "테스트 CCTV 위치",
        "count": 3,
    },
    {
        "위도": 37.5420,
        "경도": 127.0810,
        "시설유형": "가로등",
        "주소": "테스트 가로등 위치",
        "count": 1,
    },
    {
        "위도": 37.5370,
        "경도": 127.0850,
        "시설유형": "비상벨",
        "주소": "테스트 비상벨 위치",
        "count": 1,
    },
    {
        "위도": 37.5390,
        "경도": 127.0795,
        "시설유형": "파출소",
        "주소": "테스트 파출소 위치",
        "count": 1,
    },
])

print("\n[1단계] 입력 시설 데이터")
print(facilities)


# ============================================================
# 2단계. 안전지수를 계산할 기준 위치 하나 정하기
# ============================================================

"""
안전지수는 '어떤 위치 기준'으로 계산해야 한다.

예를 들어,
'이 위치 주변은 안전한가?'를 알고 싶은 것이다.

지금은 테스트용으로 광진구 근처 좌표 하나를 정한다.
나중에는 이 기준 위치가 여러 개가 되고,
그게 바로 '격자점'이 된다.
"""

target_lat = 37.5400
target_lng = 127.0820

print("\n[2단계] 안전지수를 계산할 기준 위치")
print("기준 위도:", target_lat)
print("기준 경도:", target_lng)


# ============================================================
# 3단계. 기준 위치와 각 시설 사이의 거리 계산하기
# ============================================================

"""
반경 1km 안에 들어오는 시설을 찾으려면,
기준 위치와 시설 사이의 거리를 알아야 한다.

정확한 거리 계산 공식은 복잡하다.
그래서 지금은 이해용으로 쉬운 근사식을 쓴다.

서울 근처에서는 대략:
- 위도 1도 차이 ≈ 111km
- 경도 1도 차이 ≈ 88.8km

즉,
위도 차이와 경도 차이를 km로 바꾼 뒤,
피타고라스처럼 거리를 계산한다.
"""

facilities["위도차이_km"] = (facilities["위도"] - target_lat) * 111
facilities["경도차이_km"] = (facilities["경도"] - target_lng) * 88.8

facilities["거리_km"] = np.sqrt(
    facilities["위도차이_km"] ** 2
    + facilities["경도차이_km"] ** 2
)

print("\n[3단계] 기준 위치와 각 시설 사이의 거리")
print(facilities[["시설유형", "주소", "count", "거리_km"]])


# ============================================================
# 4단계. 반경 1km 안에 있는 시설만 고르기
# ============================================================

"""
우리는 '주변 1km 안'의 시설만 안전점수에 반영하려고 한다.

따라서 거리_km가 1 이하인 행만 남긴다.
"""

near_facilities = facilities[facilities["거리_km"] <= 1].copy()

print("\n[4단계] 반경 1km 안에 들어온 시설")
print(near_facilities[["시설유형", "주소", "count", "거리_km"]])


# ============================================================
# 5단계. 시설유형별 count 합계 구하기
# ============================================================

"""
이제 반경 1km 안에 들어온 시설들을 종류별로 센다.

예:
- CCTV count 합계
- 가로등 count 합계
- 비상벨 count 합계
- 파출소 count 합계

CCTV는 count가 3이면 카메라 3대로 본다.
가로등, 비상벨, 파출소는 보통 한 행을 1개로 본다.
"""

count_by_type = near_facilities.groupby("시설유형")["count"].sum()

print("\n[5단계] 반경 1km 안 시설유형별 개수")
print(count_by_type)


# ============================================================
# 6단계. 안전점수 계산에 필요한 값 꺼내기
# ============================================================

"""
groupby 결과에서 필요한 값을 꺼낸다.

만약 어떤 시설이 반경 안에 하나도 없으면,
그 값은 0으로 처리한다.

예:
반경 안에 비상벨이 없으면 bell_count = 0
"""

cctv_count = count_by_type.get("CCTV", 0)
streetlight_count = count_by_type.get("가로등", 0)
bell_count = count_by_type.get("비상벨", 0)
police_count = count_by_type.get("파출소", 0)

print("\n[6단계] 점수 계산에 쓸 값")
print("CCTV 개수:", cctv_count)
print("가로등 개수:", streetlight_count)
print("비상벨 개수:", bell_count)
print("경찰시설 개수:", police_count)


# ============================================================
# 7단계. 개수를 0~1 점수로 바꾸기
# ============================================================

"""
시설마다 숫자의 크기가 다르다.

예:
- CCTV는 주변에 30대 있을 수도 있음
- 경찰서는 주변에 1개만 있어도 의미 있음

그래서 그냥 더하지 않고,
각 시설 개수를 0~1 사이 값으로 바꾼다.

여기서는 임시 기준을 이렇게 둔다.

CCTV 30대 이상이면 cctv_score = 1
가로등 60개 이상이면 streetlight_score = 1
비상벨 10개 이상이면 bell_score = 1
경찰시설 2개 이상이면 police_score = 1
"""

cctv_score = min(cctv_count / 30, 1)
streetlight_score = min(streetlight_count / 60, 1)
bell_score = min(bell_count / 10, 1)
police_score = min(police_count / 2, 1)

print("\n[7단계] 0~1 사이로 바꾼 시설 점수")
print("CCTV 점수:", cctv_score)
print("가로등 점수:", streetlight_score)
print("비상벨 점수:", bell_score)
print("경찰시설 점수:", police_score)


# ============================================================
# 8단계. 최종 안전점수 계산하기
# ============================================================

"""
기본점수는 50점으로 둔다.

그 이유:
- 시설이 하나도 없다고 무조건 0점으로 두면 너무 극단적이다.
- 50점을 보통 상태로 두고,
  안전시설이 많을수록 점수를 올리는 방식이다.

현재 임시 공식:
안전점수 =
50
+ CCTV 점수 * 20
+ 가로등 점수 * 15
+ 비상벨 점수 * 10
+ 경찰시설 점수 * 15
"""

safety_score = (
    50
    + cctv_score * 20
    + streetlight_score * 15
    + bell_score * 10
    + police_score * 15
)

# 점수가 100을 넘지 않게 제한
safety_score = min(safety_score, 100)

print("\n[8단계] 최종 안전점수")
print("safety_score:", safety_score)


# ============================================================
# 9단계. 안전점수를 A~E 등급으로 바꾸기
# ============================================================

"""
점수만 있으면 보기 어렵기 때문에 등급으로 바꾼다.

A: 80점 이상
B: 65점 이상
C: 50점 이상
D: 35점 이상
E: 35점 미만
"""

if safety_score >= 80:
    grade = "A"
elif safety_score >= 65:
    grade = "B"
elif safety_score >= 50:
    grade = "C"
elif safety_score >= 35:
    grade = "D"
else:
    grade = "E"

print("\n[9단계] 안전등급")
print("grade:", grade)


# ============================================================
# 10단계. 최종 결과표 만들기
# ============================================================

"""
최종적으로 UI 담당이나 경로 담당에게 넘길 수 있는 표를 만든다.

지금은 기준 위치가 하나뿐이라 결과도 한 줄이다.
나중에는 기준 위치가 여러 개가 되고,
그 결과가 여러 줄짜리 safety_grid.csv가 된다.
"""

result = pd.DataFrame([
    {
        "위도": target_lat,
        "경도": target_lng,
        "cctv_count_1km": cctv_count,
        "streetlight_count_1km": streetlight_count,
        "bell_count_1km": bell_count,
        "police_count_1km": police_count,
        "safety_score": safety_score,
        "grade": grade,
    }
])

print("\n[10단계] 최종 결과표")
print(result)


# ============================================================
# 11단계. CSV로 저장하기
# ============================================================

"""
최종 결과를 data/processed/safety_sample.csv로 저장한다.

이 파일은 나중에 UI 담당이 읽어서
지도 위에 안전점수나 등급을 표시할 수 있다.
"""

output_dir = Path("data/processed")
output_dir.mkdir(parents=True, exist_ok=True)

output_path = output_dir / "safety_sample.csv"

result.to_csv(output_path, index=False, encoding="utf-8-sig")

print("\n[11단계] CSV 저장 완료")
print("저장 위치:", output_path)